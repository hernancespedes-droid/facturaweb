-- MA Maestro de clientes, con los campos de clientes.dbf (nombres largos de datos.dbc). Algunos textos se
-- agrandaron respecto del VFP (razón social, domicilio, observaciones, mails). Agregado en la web: activo.
CREATE TABLE IF NOT EXISTS clientes (
  codigo            INT UNSIGNED  NOT NULL,
  razon_social      VARCHAR(100)  NOT NULL,
  domicilio         VARCHAR(80)   NULL,
  localidad         VARCHAR(40)   NULL,
  codigo_postal     VARCHAR(8)    NULL,
  provincia         VARCHAR(2) COLLATE utf8mb4_bin NULL,
  iva               TINYINT UNSIGNED NOT NULL COMMENT '1 Inscripto, 2 No Inscripto, 3 Consumidor Final, 4 Exento (B), 5 Exento (A), 6 Liberado, 7 Monotributo, 8 Exento Especial (A), 9 Exento Especial (B)',
  cuit              BIGINT UNSIGNED NULL,
  credito           DECIMAL(12,2) NOT NULL DEFAULT 0,
  tipo_cliente      VARCHAR(2) COLLATE utf8mb4_bin NULL,
  telefono          VARCHAR(60)   NULL,
  fax               VARCHAR(60)   NULL,
  fecha_alta        DATE          NULL,
  alta_x_sistema    TINYINT(1)    NOT NULL DEFAULT 0,
  observaciones     VARCHAR(255)  NULL,
  ultima_compra     DATE          NULL,
  calcula_impuesto  TINYINT(1)    NOT NULL DEFAULT 0,
  vendedor          VARCHAR(2) COLLATE utf8mb4_bin NULL,
  lista_2_fija      TINYINT(1)    NOT NULL DEFAULT 0,
  descuento         DECIMAL(5,2)  NOT NULL DEFAULT 0,
  lista_habitual    VARCHAR(3)    NULL,
  forma_pago        TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '1 Contado, 2 Cuenta corriente',
  nombre_fantasia   VARCHAR(100)  NULL,
  actualizacion     DATETIME      NULL,
  condicionpago     VARCHAR(2) COLLATE utf8mb4_bin NULL,
  consignacion      TINYINT(1)    NOT NULL DEFAULT 0,
  transporte        SMALLINT UNSIGNED NULL,
  cta_bruto         SMALLINT UNSIGNED NULL,
  cta_iva1          SMALLINT UNSIGNED NULL,
  cta_iva2          SMALLINT UNSIGNED NULL,
  cta_neto          SMALLINT UNSIGNED NULL,
  emailfc           VARCHAR(255)  NULL COMMENT 'Mails para enviar las facturas (separados por ;)',
  emaillis          VARCHAR(255)  NULL COMMENT 'Mails para listados / resúmenes',
  activo            TINYINT(1)    NOT NULL DEFAULT 1,
  PRIMARY KEY (codigo),
  KEY ix_clientes_razon (razon_social),
  KEY ix_clientes_cuit (cuit)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
